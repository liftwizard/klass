package cool.klass.model.converter.compiler.annotation;

import java.util.LinkedHashSet;
import java.util.List;
import java.util.Optional;

import javax.annotation.Nonnull;

import cool.klass.model.converter.compiler.CompilationUnit;
import cool.klass.model.converter.compiler.state.IAntlrElement;
import cool.klass.model.converter.compiler.state.TokenRange;
import cool.klass.model.converter.compiler.syntax.highlighter.ansi.AnsiTokenColorizer;
import cool.klass.model.converter.compiler.syntax.highlighter.ansi.scheme.AnsiColorScheme;
import cool.klass.model.converter.compiler.token.categories.TokenCategories;
import org.antlr.v4.runtime.ParserRuleContext;
import org.antlr.v4.runtime.Token;
import org.eclipse.collections.api.factory.Lists;
import org.eclipse.collections.api.list.ImmutableList;
import org.eclipse.collections.api.list.MutableList;
import org.eclipse.collections.api.set.MutableSet;
import org.eclipse.collections.api.tuple.Pair;
import org.eclipse.collections.impl.set.mutable.SetAdapter;
import org.eclipse.collections.impl.tuple.Tuples;
import org.fusesource.jansi.Ansi;
import org.fusesource.jansi.Ansi.Color;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * Renders compiler annotations as text, with syntax-colored source snippets and optional IDE links.
 * Annotations are pure data, so the color scheme and the IDE-link setting live here instead, chosen by the caller and combined with the TokenCategories of the CompilationResult.
 */
public final class CompilerAnnotationRenderer
{
	private static final Logger LOGGER = LoggerFactory.getLogger(CompilerAnnotationRenderer.class);

	@Nonnull
	private final AnsiTokenColorizer ansiTokenColorizer;

	private final boolean enableIdeLinks;

	public CompilerAnnotationRenderer(
		@Nonnull AnsiColorScheme colorScheme,
		@Nonnull TokenCategories tokenCategories,
		boolean enableIdeLinks
	)
	{
		this.ansiTokenColorizer = new AnsiTokenColorizer(colorScheme, tokenCategories);
		this.enableIdeLinks = enableIdeLinks;
	}

	@Nonnull
	public String render(@Nonnull RootCompilerAnnotation annotation)
	{
		Color caretColor = CompilerAnnotationRenderer.getCaretColor(annotation.getSeverity());
		String contextString = this.getContextString(annotation, caretColor);
		String locationMessage = CompilerAnnotationRenderer.getOptionalLocationMessage(annotation);
		String causeString = this.getCauseString(annotation);
		String ideUrlMessage = this.getIdeUrlMessage(annotation);
		String severityName = annotation.isError() ? "Error" : "Warning";

		// Avoid Ansi.render(): Maven 3.10's org.fusesource.jansi compatibility shim ignores Ansi.isEnabled() there
		String annotationCodeString = Ansi.ansi()
			.fg(Color.MAGENTA)
			.a(annotation.getAnnotationCode())
			.reset()
			.toString();
		String headlineString = Ansi.ansi()
			.fg(caretColor)
			.a(severityName + ": " + annotation.getMessage())
			.reset()
			.toString();

		var format = """
			════════════════════════════════════════ %s ════════════════════════════════════════
			%s

			At %s

			%s%s%s%s
			═════════════════════════════════════════════════════════════════════════════════════════════
			""";

		return String.format(
			format,
			annotationCodeString,
			headlineString,
			CompilerAnnotationRenderer.getShortLocationString(annotation),
			contextString,
			locationMessage,
			causeString,
			ideUrlMessage
		);
	}

	@Nonnull
	private String renderCause(@Nonnull CauseCompilerAnnotation cause)
	{
		String contextString = this.getContextString(cause, Color.GREEN);
		String locationMessage = CompilerAnnotationRenderer.getOptionalLocationMessage(cause);
		String causeString = this.getCauseString(cause);

		return (
			"\n" +
			"Which was generated by macro at location " +
			CompilerAnnotationRenderer.getShortLocationString(cause) +
			"\n" +
			contextString +
			locationMessage +
			causeString
		);
	}

	@Nonnull
	private static Color getCaretColor(@Nonnull AnnotationSeverity severity)
	{
		return switch (severity)
		{
			case ERROR -> Color.RED;
			case WARNING -> Color.YELLOW;
		};
	}

	@Nonnull
	private String getCauseString(@Nonnull AbstractCompilerAnnotation annotation)
	{
		return annotation.getMacroCause().map(this::renderCause).orElse("");
	}

	private String getContextString(@Nonnull AbstractCompilerAnnotation annotation, @Nonnull Color caretColor)
	{
		ImmutableList<AbstractContextString> contextStrings = this.getContextStrings(annotation, caretColor);

		int lineNumberWidth = contextStrings.collectInt(AbstractContextString::getLineNumberWidth).max();

		String entireContext = contextStrings
			.collectWith(AbstractContextString::toString, lineNumberWidth)
			.makeString("", "\n", "\n");
		return Ansi.ansi().a(entireContext).reset().toString();
	}

	private ImmutableList<AbstractContextString> getContextStrings(
		@Nonnull AbstractCompilerAnnotation annotation,
		@Nonnull Color caretColor
	)
	{
		SnippetSource snippetSource = annotation.getSnippetSource();
		MutableSet<Token> contextTokens = CompilerAnnotationRenderer.getContextTokens(annotation);

		MutableSet<Token> underlinedTokens = annotation
			.getOffendingContexts()
			.asLazy()
			.flatCollectWith(CompilerAnnotationRenderer::getUnderlinedTokenRange, snippetSource)
			.into(SetAdapter.adapt(new LinkedHashSet<>()));

		if (!contextTokens.containsAll(underlinedTokens))
		{
			String message = annotation
				.getOffendingContexts()
				.asLazy()
				.flatCollectWith(CompilerAnnotationRenderer::getUnderlinedTokenRange, snippetSource)
				.collect(Token::getText)
				.toList()
				.makeString("");
			LOGGER.warn("Not all underlined tokens are in the context: {}", message);
		}

		MutableSet<Pair<CompilationUnit, Integer>> underlinedLines = underlinedTokens.collect((token) ->
			Tuples.pair(snippetSource.getCompilationUnit(token), token.getLine())
		);

		ImmutableList<TokenLine> tokenLines = snippetSource.getTokenLines(contextTokens);
		MutableList<AbstractContextString> contextStrings = Lists.mutable.empty();

		for (TokenLine tokenLine : tokenLines)
		{
			Ansi ansi = Ansi.ansi();
			tokenLine.getTokens().forEach((token) -> this.ansiTokenColorizer.colorizeText(ansi, token));

			if (!ansi.toString().endsWith(System.getProperty("line.separator")))
			{
				ansi.newline();
			}
			contextStrings.add(new ContextString(tokenLine.getLine(), ansi.toString(), tokenLine.isGenerated()));
			if (underlinedLines.contains(Tuples.pair(tokenLine.getCompilationUnit(), tokenLine.getLine())))
			{
				String underline = CompilerAnnotationRenderer.getUnderline(tokenLine, underlinedTokens, caretColor);
				contextStrings.add(new UnderlineContextString(tokenLine.getLine(), underline));
			}
		}

		return contextStrings.toImmutable();
	}

	@Nonnull
	private static MutableSet<Token> getContextTokens(@Nonnull AbstractCompilerAnnotation annotation)
	{
		SnippetSource snippetSource = annotation.getSnippetSource();
		MutableSet<Token> contextTokens = SetAdapter.adapt(new LinkedHashSet<>());

		annotation
			.getSourceContexts()
			.asReversed()
			.collect(IAntlrElement::getContextBefore)
			.flatCollectWith(CompilerAnnotationRenderer::getTokens, snippetSource)
			.into(contextTokens);

		annotation
			.getSourceContexts()
			.asLazy()
			.collect(IAntlrElement::getContextAfter)
			.select(Optional::isPresent)
			.collect(Optional::get)
			.flatCollectWith(CompilerAnnotationRenderer::getTokens, snippetSource)
			.into(contextTokens);
		return contextTokens;
	}

	private static String getUnderline(
		TokenLine tokenLine,
		MutableSet<Token> underlinedTokens,
		@Nonnull Color caretColor
	)
	{
		String uncoloredString = tokenLine
			.getTokens()
			.collectWith(CompilerAnnotationRenderer::getSpaceOrUnderline, underlinedTokens)
			.makeString("")
			.stripTrailing();

		return Ansi.ansi()
			.fg(caretColor)
			.a(uncoloredString + "\n")
			.toString();
	}

	private static String getSpaceOrUnderline(Token token, MutableSet<Token> underlinedTokens)
	{
		String text = token.getText();
		if (underlinedTokens.contains(token))
		{
			return "^".repeat(text.length());
		}
		// Keep tabs so the carets line up under source lines indented with tabs.
		return text.replaceAll("[^\t]", " ");
	}

	private static ImmutableList<Token> getUnderlinedTokenRange(
		@Nonnull ParserRuleContext ctx,
		@Nonnull SnippetSource snippetSource
	)
	{
		return CompilerAnnotationRenderer.getTokens(new TokenRange(ctx.getStart(), ctx.getStop()), snippetSource);
	}

	private static ImmutableList<Token> getTokens(@Nonnull TokenRange tokenRange, @Nonnull SnippetSource snippetSource)
	{
		List<Token> tokens = snippetSource
			.getTokenStream(tokenRange.start())
			.get(tokenRange.start().getTokenIndex(), tokenRange.stop().getTokenIndex());
		return Lists.immutable.withAll(tokens);
	}

	private static String getShortLocationString(@Nonnull AbstractCompilerAnnotation annotation)
	{
		if (annotation.getMacroCause().isPresent())
		{
			return String.format("(%s)", annotation.getCompilationUnit());
		}
		return String.format(
			"(%s:%d:%d)",
			annotation.getCompilationUnit().getFilenameWithoutDirectory(),
			annotation.getLine(),
			annotation.getCharPositionInLine() + 1
		);
	}

	@Nonnull
	private static String getOptionalLocationMessage(@Nonnull AbstractCompilerAnnotation annotation)
	{
		if (annotation.getMacroCause().isPresent())
		{
			return "";
		}
		// @formatter:off
		return Ansi.ansi().a("\n")
				.fg(Color.CYAN).a("Location:  ").reset().a(annotation.getCompilationUnit().getFilenameWithoutDirectory()).a(":").a(annotation.getLine()).a(":").a(annotation.getCharPositionInLine() + 1).reset().a("\n")
				.fg(Color.CYAN).a("File:      ").reset().a(annotation.getCompilationUnit()).reset().a("\n")
				.fg(Color.CYAN).a("Line:      ").reset().a(annotation.getLine()).reset().a("\n")
				.fg(Color.CYAN).a("Character: ").reset().a(annotation.getCharPositionInLine() + 1)
				.toString();
		// @formatter:on
	}

	@Nonnull
	private String getIdeUrlMessage(@Nonnull RootCompilerAnnotation annotation)
	{
		if (!this.enableIdeLinks)
		{
			return "";
		}

		String absolutePath = annotation.getCompilationUnit().getSourceName();
		int line = annotation.getLine();
		int column = annotation.getCharPositionInLine() + 1;

		String vscodeUrl = String.format("vscode://file/%s:%d:%d", absolutePath, line, column);
		String jetbrainsUrl = String.format(
			"jetbrains://idea/navigate/reference?project=&file=%s&line=%d&column=%d",
			absolutePath,
			line,
			column
		);

		// @formatter:off
		return Ansi.ansi().a("\n")
				.fg(Color.CYAN).a("VS Code:   ").reset().a(vscodeUrl).a("\n")
				.fg(Color.CYAN).a("JetBrains: ").reset().a(jetbrainsUrl)
				.toString();
		// @formatter:on
	}
}
