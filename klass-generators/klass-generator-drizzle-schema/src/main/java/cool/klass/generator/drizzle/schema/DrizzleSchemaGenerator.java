package cool.klass.generator.drizzle.schema;

import java.nio.file.Path;
import java.util.Objects;

import javax.annotation.Nonnull;

import cool.klass.generator.perpackage.AbstractPerPackageGenerator;
import cool.klass.model.meta.domain.api.DomainModel;
import cool.klass.model.meta.domain.api.Klass;
import org.eclipse.collections.api.factory.SortedSets;
import org.eclipse.collections.api.list.ImmutableList;
import org.eclipse.collections.api.set.sorted.MutableSortedSet;

public class DrizzleSchemaGenerator
	extends AbstractPerPackageGenerator
{
	private final String fileName;

	public DrizzleSchemaGenerator(DomainModel domainModel)
	{
		this(domainModel, "schema.ts");
	}

	public DrizzleSchemaGenerator(DomainModel domainModel, String fileName)
	{
		super(domainModel);
		this.fileName = Objects.requireNonNull(fileName);
	}

	@Nonnull
	@Override
	protected Path getPluginRelativePath(Path path)
	{
		return path.resolve("drizzle").resolve("schema");
	}

	@Override
	@Nonnull
	protected String getFileName()
	{
		return this.fileName;
	}

	@Override
	@Nonnull
	protected String getPackageSourceCode(@Nonnull String fullyQualifiedPackage)
	{
		return getSourceCode(this.domainModel, fullyQualifiedPackage);
	}

	public static String getSourceCode(DomainModel domainModel, String fullyQualifiedPackage)
	{
		ImmutableList<Klass> classes = domainModel
			.getClasses()
			.select((each) -> each.getPackageName().equals(fullyQualifiedPackage));

		MutableSortedSet<String> sqliteCoreImports = SortedSets.mutable.with("sqliteTable");
		ImmutableList<String> tables = classes.collect((klass) ->
			DrizzleTableGenerator.getTable(klass, sqliteCoreImports)
		);
		boolean usesSql = tables.anySatisfy((table) -> table.contains("sql`"));

		String sqlImport = usesSql ? "import {sql} from \"drizzle-orm\";\n" : "";

		return (
			"// Generated by Klass (" +
			DrizzleSchemaGenerator.class.getCanonicalName() +
			"). Do not edit by hand.\n" +
			"\n" +
			sqlImport +
			"import {" +
			sqliteCoreImports.makeString(", ") +
			"} from \"drizzle-orm/sqlite-core\";\n" +
			"\n" +
			tables.makeString("\n")
		);
	}
}
